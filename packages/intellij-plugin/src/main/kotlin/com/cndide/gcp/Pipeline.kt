package com.cndide.gcp

import java.io.File

/** Builds gcloud command lines and the Cloud Build pipeline for a Cloud Native Development project. */
object Pipeline {
    val ENVS = listOf("dev", "sit", "uat", "prod")

    /** `gcloud <args> --project P [--impersonate-service-account SA]` */
    fun gcloud(cnd: CndProject, vararg args: String): List<String> {
        val cmd = mutableListOf(GcpClient.gcloud(), *args)
        cmd += "--project=${cnd.projectId}"
        if (cnd.impersonate.isNotBlank()) cmd += "--impersonate-service-account=${cnd.impersonate}"
        return cmd
    }

    fun hasPipeline(base: String?): Boolean = base != null && File(base, "cloudbuild.yaml").exists()

    fun hasDockerfile(base: String?): Boolean = base != null && File(base, "Dockerfile").exists()

    /** cloudbuild.yaml: build, push to Artifact Registry and deploy to Cloud Run for the chosen environment. */
    fun cloudBuildYaml(withDockerfile: Boolean): String {
        val image = "\${_REGION}-docker.pkg.dev/\$PROJECT_ID/\${_REPO}/\${_SERVICE}-\${_ENV}:\$BUILD_ID"
        return if (withDockerfile) {
            """# Generated by Cloud Native Development IDE
steps:
  - id: build
    name: gcr.io/cloud-builders/docker
    args: ['build', '-t', '$image', '.']
  - id: push
    name: gcr.io/cloud-builders/docker
    args: ['push', '$image']
  - id: deploy
    name: gcr.io/google.com/cloudsdktool/cloud-sdk
    entrypoint: gcloud
    args:
      - run
      - deploy
      - '${'$'}{_SERVICE}-${'$'}{_ENV}'
      - '--image=$image'
      - '--region=${'$'}{_REGION}'
      - '--labels=environment=${'$'}{_ENV},managed-by=cloud-native-studio'
      - '--no-allow-unauthenticated'
images:
  - '$image'
substitutions:
  _ENV: dev
  _SERVICE: app
  _REGION: us-central1
  _REPO: cnd-apps
options:
  logging: CLOUD_LOGGING_ONLY
"""
        } else {
            """# Generated by Cloud Native Development IDE (no Dockerfile found: deploys from source with buildpacks)
steps:
  - id: deploy
    name: gcr.io/google.com/cloudsdktool/cloud-sdk
    entrypoint: gcloud
    args:
      - run
      - deploy
      - '${'$'}{_SERVICE}-${'$'}{_ENV}'
      - '--source=.'
      - '--region=${'$'}{_REGION}'
      - '--labels=environment=${'$'}{_ENV},managed-by=cloud-native-studio'
      - '--no-allow-unauthenticated'
substitutions:
  _ENV: dev
  _SERVICE: app
  _REGION: us-central1
  _REPO: cnd-apps
options:
  logging: CLOUD_LOGGING_ONLY
"""
        }
    }

    fun submit(cnd: CndProject): List<String> = gcloud(
        cnd, "builds", "submit", "--config=cloudbuild.yaml",
        "--substitutions=_ENV=${cnd.env},_SERVICE=${cnd.service},_REGION=${cnd.region},_REPO=${cnd.repo}", ".",
    )

    fun deploy(cnd: CndProject): List<String> = gcloud(
        cnd, "run", "deploy", cnd.envService, "--source=.", "--region=${cnd.region}",
        "--labels=environment=${cnd.env},managed-by=cloud-native-studio", "--no-allow-unauthenticated", "--quiet",
    )

    data class ResourceKind(val label: String, val defaultName: (CndProject) -> String, val command: (CndProject, String) -> List<String>)

    val RESOURCES = listOf(
        ResourceKind("Cloud Storage bucket", { "${it.projectId}-${it.env}-${it.service}-data" }) { c, n ->
            gcloud(c, "storage", "buckets", "create", "gs://$n", "--location=${c.region}", "--uniform-bucket-level-access")
        },
        ResourceKind("Artifact Registry (Docker) repository", { it.repo }) { c, n ->
            gcloud(c, "artifacts", "repositories", "create", n, "--repository-format=docker", "--location=${c.region}")
        },
        ResourceKind("Pub/Sub topic", { "${it.service}-${it.env}-events" }) { c, n ->
            gcloud(c, "pubsub", "topics", "create", n, "--labels=environment=${c.env}")
        },
        ResourceKind("Secret Manager secret", { "${it.service}-${it.env}-secret" }) { c, n ->
            gcloud(c, "secrets", "create", n, "--replication-policy=automatic", "--labels=environment=${c.env}")
        },
    )
}
