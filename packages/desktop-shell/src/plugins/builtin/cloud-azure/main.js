/** Azure connector. Identity = the Azure CLI login; scope = subscription. */
const { spawn } = require('child_process');

exports.activate = (ctx) => {
  const { exec, commandLine, isMissing } = ctx;

  const GUID_RE = /^[0-9a-fA-F]{8}-([0-9a-fA-F]{4}-){3}[0-9a-fA-F]{12}$/;
  const REGION_RE = /^[a-z]+[a-z0-9]*$/;
  const GROUP_RE = /^[A-Za-z0-9._()-]{1,90}$/;

  const az = (proj, args) => commandLine('az', [...args, `--subscription=${proj.scope}`]);

  // Per-kind naming rules (Azure is strict and differs per resource type).
  const RESOURCES = {
    group: { label: 'Resource group', re: GROUP_RE, name: (p) => p.group, build: (p, n) => ['group', 'create', `--name=${n}`, `--location=${p.region}`, '--tags', `environment=${p.env}`, 'managed-by=cloud-native-studio'] },
    storage: { label: 'Storage account', re: /^[a-z0-9]{3,24}$/, name: (p) => `${p.service.replace(/[^a-z0-9]/g, '')}${p.env}data`.slice(0, 24), build: (p, n) => ['storage', 'account', 'create', `--name=${n}`, `--resource-group=${p.group}`, `--location=${p.region}`, '--sku=Standard_LRS', '--allow-blob-public-access=false', `--tags=environment=${p.env}`] },
    acr: { label: 'Container registry', re: /^[a-zA-Z0-9]{5,50}$/, name: (p) => `${p.service.replace(/[^a-z0-9]/g, '')}${p.env}acr`.slice(0, 50), build: (p, n) => ['acr', 'create', `--name=${n}`, `--resource-group=${p.group}`, `--location=${p.region}`, '--sku=Basic', `--tags=environment=${p.env}`] },
    keyvault: { label: 'Key Vault', re: /^[a-zA-Z][a-zA-Z0-9-]{1,22}[a-zA-Z0-9]$/, name: (p) => `${p.service}-${p.env}-kv`.slice(0, 24), build: (p, n) => ['keyvault', 'create', `--name=${n}`, `--resource-group=${p.group}`, `--location=${p.region}`, `--tags=environment=${p.env}`] },
  };

  const pipelineYaml = () => [
    '# Generated by Cloud Native Studio (Azure Pipelines)',
    'trigger:', '  branches:', '    include: [main]',
    'pool:', '  vmImage: ubuntu-latest',
    'variables:', '  service: app', '  environment: dev', '  resourceGroup: app-dev-rg', '  location: eastus',
    'steps:',
    '  - task: AzureCLI@2',
    '    displayName: Build and deploy to Azure Container Apps',
    '    inputs:',
    '      azureSubscription: $(serviceConnection)',
    '      scriptType: bash',
    '      scriptLocation: inlineScript',
    '      inlineScript: |',
    '        az containerapp up --name $(service)-$(environment) --resource-group $(resourceGroup) \\',
    '          --location $(location) --source . --ingress internal',
    '',
  ].join('\n');

  ctx.cloud.register({
    id: 'azure', name: 'Microsoft Azure', short: 'Azure', kind: 'public', color: '#0078d4',
    cli: { cmd: 'az', install: 'https://learn.microsoft.com/cli/azure/install-azure-cli' },
    scopeLabel: 'Subscription',
    defaultRegion: 'eastus',
    regions: ['eastus', 'eastus2', 'westus2', 'westeurope', 'northeurope', 'centralindia', 'southeastasia', 'australiaeast'],
    validateScope: (s) => GUID_RE.test(s),
    validateRegion: (r) => REGION_RE.test(r),
    consoleUrl: () => 'https://portal.azure.com/',

    async status() {
      const r = await exec('az', ['account', 'show', '-o', 'json'], { timeout: 40000 });
      if (isMissing(r)) return { installed: false, signedIn: false, identity: '', scope: '', detail: 'Azure CLI not found' };
      if (!r.ok) return { installed: true, signedIn: false, identity: '', scope: '', detail: 'Not signed in' };
      let a = {};
      try { a = JSON.parse(r.out); } catch { /* ignore */ }
      return { installed: true, signedIn: true, identity: (a.user && a.user.name) || 'Azure identity', scope: a.id || '', detail: `${a.name || 'subscription'}${a.tenantId ? ` · tenant ${String(a.tenantId).slice(0, 8)}…` : ''}`, scopeName: a.name || '' };
    },

    login(emit) {
      const child = spawn('az login', { shell: true, windowsHide: false });
      child.stdout.on('data', (d) => emit('log', d.toString()));
      child.stderr.on('data', (d) => emit('log', d.toString()));
      child.on('error', (e) => emit('log', `az error: ${e.message}`));
      child.on('close', (code) => emit('done', code));
    },

    async logout() {
      await exec('az', ['logout'], { timeout: 30000 });
    },

    async scopes() {
      const r = await exec('az', ['account', 'list', '--query', '[].{id:id,name:name,state:state}', '-o', 'json'], { timeout: 40000 });
      if (!r.ok) throw new Error(isMissing(r) ? 'Azure CLI not found.' : r.err.split(/\r?\n/)[0]);
      return JSON.parse(r.out || '[]').filter((s) => GUID_RE.test(s.id)).map((s) => ({ id: s.id, name: s.name, detail: s.state }));
    },

    async setScope(id) {
      if (!GUID_RE.test(id)) throw new Error('Invalid subscription id.');
      const r = await exec('az', ['account', 'set', `--subscription=${id}`], { timeout: 30000 });
      if (!r.ok) throw new Error(r.err.split(/\r?\n/)[0]);
      return {};
    },

    async inventory(scope) {
      if (!GUID_RE.test(scope)) throw new Error('Select a subscription first.');
      const r = await exec('az', ['resource', 'list', `--subscription=${scope}`, '--query', '[].{t:type,l:location}', '-o', 'json'], { timeout: 60000 });
      if (!r.ok) throw new Error(r.err.split(/\r?\n/)[0] || 'Unable to list resources (needs Reader access).');
      const counts = new Map();
      for (const x of JSON.parse(r.out || '[]')) counts.set(x.t, (counts.get(x.t) || 0) + 1);
      return [...counts.entries()].sort().map(([t, n]) => {
        const ns = t.split('/')[0].replace('Microsoft.', '');
        return { category: ns, title: t.split('/').slice(1).join('/'), detail: `${n} found`, count: n, url: 'https://portal.azure.com/#view/HubsExtension/BrowseAll' };
      });
    },

    actions: {
      generatePipeline: () => ({ path: 'azure-pipelines.yml', content: pipelineYaml() }),

      // Runs an existing Azure DevOps pipeline named <service>-<env> (needs the azure-devops CLI extension).
      pipeline: (proj) => ({
        title: `Azure Pipelines ${proj.service}-${proj.env}`,
        command: commandLine('az', ['pipelines', 'run', `--name=${proj.service}-${proj.env}`]),
      }),

      deploy: (proj) => {
        if (!GROUP_RE.test(proj.group)) throw new Error('Set a valid resource group for this project.');
        return {
          title: `Deploy ${proj.service}-${proj.env}`,
          command: az(proj, ['containerapp', 'up', `--name=${proj.service}-${proj.env}`, `--resource-group=${proj.group}`, `--location=${proj.region}`, '--source=.', '--ingress=internal']),
        };
      },

      resourceKinds: (proj) => Object.entries(RESOURCES).map(([id, r]) => ({ id, label: r.label, defaultName: r.name(proj) })),

      resource: (proj, params) => {
        const r = RESOURCES[params.type];
        if (!r) throw new Error('Unknown resource type.');
        const name = String(params.name || '').trim();
        if (!r.re.test(name)) throw new Error(`Invalid name for a ${r.label.toLowerCase()}.`);
        if (params.type !== 'group' && !GROUP_RE.test(proj.group)) throw new Error('Set a valid resource group first.');
        return { title: `Create ${name}`, command: az(proj, r.build(proj, name)) };
      },

      bootstrap: (proj, envs) => ({
        path: 'infra/cnd-bootstrap/azure/main.tf',
        content: [
          '# Generated by Cloud Native Studio (Azure)',
          'terraform {', '  required_providers { azurerm = { source = "hashicorp/azurerm", version = "~> 3.0" } }', '}',
          'provider "azurerm" {', '  features {}', `  subscription_id = "${proj.scope}"`, '}', '',
          ...envs.map((e) => `resource "azurerm_resource_group" "${e}" {\n  name     = "${proj.service}-${e}-rg"\n  location = "${proj.region}"\n  tags     = { environment = "${e}", managed-by = "cloud-native-studio" }\n}\n`),
        ].join('\n'),
      }),
    },
  });
};
