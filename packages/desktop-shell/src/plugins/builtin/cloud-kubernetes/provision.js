/**
 * Kubernetes (private / on-prem / hybrid) landing zone: one NAMESPACE per environment in the selected cluster.
 *   Cluster context
 *     ├─ <app>-dev    namespace + quota + limits + default-deny network policy + deployer service account (namespace-only role)
 *     ├─ <app>-uat
 *     └─ <app>-prod   same + Pod Security "restricted", larger quota
 * A namespace is the unit Kubernetes scopes access (RBAC), quota, network policy and deletion to. Developers deploy as the namespace's
 * deployer service account (kubectl --as=...), so a mistake in dev cannot touch prod. For stronger isolation use a cluster per environment;
 * the same manifests apply there.
 */
const MANIFEST_DIR = 'infra/cnd-environments/k8s';

function manifest(app, env, prot) {
  const ns = `${app}-${env}`;
  const labels = `    app.kubernetes.io/part-of: ${app}\n    environment: ${env}\n    managed-by: nativity-studio`;
  return [
    '# Generated by Nativity Studio',
    'apiVersion: v1', 'kind: Namespace', 'metadata:', `  name: ${ns}`, '  labels:', labels,
    `    pod-security.kubernetes.io/enforce: ${prot ? 'restricted' : 'baseline'}`, `    pod-security.kubernetes.io/warn: restricted`,
    '---', 'apiVersion: v1', 'kind: ResourceQuota', 'metadata:', '  name: environment-quota', `  namespace: ${ns}`, 'spec:', '  hard:',
    `    requests.cpu: "${prot ? 16 : 4}"`, `    requests.memory: ${prot ? '32Gi' : '8Gi'}`, `    limits.cpu: "${prot ? 32 : 8}"`, `    limits.memory: ${prot ? '64Gi' : '16Gi'}`, `    pods: "${prot ? 200 : 50}"`,
    '---', 'apiVersion: v1', 'kind: LimitRange', 'metadata:', '  name: default-limits', `  namespace: ${ns}`, 'spec:', '  limits:', '    - type: Container', '      default: { cpu: 500m, memory: 512Mi }', '      defaultRequest: { cpu: 100m, memory: 128Mi }',
    '---', 'apiVersion: networking.k8s.io/v1', 'kind: NetworkPolicy', 'metadata:', '  name: default-deny-ingress', `  namespace: ${ns}`, 'spec:', '  podSelector: {}', '  policyTypes: [Ingress]',
    '---', 'apiVersion: networking.k8s.io/v1', 'kind: NetworkPolicy', 'metadata:', '  name: allow-same-namespace', `  namespace: ${ns}`, 'spec:', '  podSelector: {}', '  policyTypes: [Ingress]', '  ingress:', '    - from:', '        - podSelector: {}',
    '---', 'apiVersion: v1', 'kind: ServiceAccount', 'metadata:', '  name: deployer', `  namespace: ${ns}`, '  labels:', labels,
    '---', 'apiVersion: rbac.authorization.k8s.io/v1', 'kind: Role', 'metadata:', '  name: deployer', `  namespace: ${ns}`, 'rules:',
    '  - apiGroups: ["", "apps", "batch", "networking.k8s.io", "autoscaling"]', '    resources: ["deployments", "statefulsets", "daemonsets", "jobs", "cronjobs", "pods", "pods/log", "services", "configmaps", "ingresses", "horizontalpodautoscalers", "persistentvolumeclaims"]', '    verbs: ["get", "list", "watch", "create", "update", "patch", "delete"]',
    '  - apiGroups: [""]', '    resources: ["secrets"]', '    verbs: ["get", "list", "create", "update", "patch"]',
    '---', 'apiVersion: rbac.authorization.k8s.io/v1', 'kind: RoleBinding', 'metadata:', '  name: deployer', `  namespace: ${ns}`, 'subjects:', '  - kind: ServiceAccount', '    name: deployer', `    namespace: ${ns}`, 'roleRef:', '  apiGroup: rbac.authorization.k8s.io', '  kind: Role', '  name: deployer',
    '',
  ].join('\n');
}

exports.build = (ctx, helpers) => {
  const { exec } = ctx;
  const { CTX_RE } = helpers;

  async function discover() {
    const r = await exec('kubectl', ['config', 'current-context'], { timeout: 15000 });
    if (!r.ok || !r.out) return { signedIn: false, context: '', namespaces: [] };
    const context = r.out.trim();
    const ns = await exec('kubectl', ['get', 'namespaces', '-o', 'name', `--context=${context}`, '--request-timeout=10s'], { timeout: 20000 });
    return { signedIn: true, context, namespaces: ns.ok ? ns.out.split(/\r?\n/).map((s) => s.replace('namespace/', '').trim()).filter(Boolean) : [], namespacesDenied: !ns.ok };
  }

  async function plan(spec, disc) {
    const { app, envs } = spec;
    const context = disc.context;
    const blockers = CTX_RE.test(context) ? [] : ['Select a cluster context first.'];
    const steps = [];
    const targets = {};
    const have = new Set(disc.namespaces || []);
    for (const e of envs) {
      const ns = `${app}-${e.name}`;
      const file = `${MANIFEST_DIR}/${ns}.yaml`;
      steps.push({ id: `file-${e.name}`, env: e.name, title: `Write ${file}`, cmd: 'kubectl', args: ['version', '--client'], writeFile: { path: file, content: manifest(app, e.name, e.protected) } });
      steps.push({ id: `apply-${e.name}`, env: e.name, mutating: true, title: `Apply namespace ${ns} (quota, limits, network policy, RBAC)`, cmd: 'kubectl', args: ['apply', `--filename=${file}`, `--context=${context}`], timeout: 120000 });
      targets[e.name] = { namespace: ns, scope: context, impersonate: '' };
    }
    const architecture = {
      title: 'Kubernetes: one namespace per environment',
      summary: 'Each environment is a namespace in the cluster, with its own resource quota, default limits, a default-deny network policy and a deployer service account whose role is limited to that namespace. Production-like namespaces enforce the strict “restricted” Pod Security level. Use a separate cluster for production when you need hard isolation.',
      root: {
        kind: 'account', label: `Cluster ${context}`, sub: 'kubeconfig context', status: 'exists',
        children: [{
          kind: 'group', label: app, sub: 'manifests in infra/cnd-environments/k8s', status: 'new',
          children: envs.map((e) => ({
            kind: 'namespace', label: `Namespace ${app}-${e.name}`, sub: '', status: have.has(`${app}-${e.name}`) ? 'exists' : 'new', protected: e.protected,
            items: [`Quota: ${e.protected ? '16 CPU / 32 Gi' : '4 CPU / 8 Gi'} requests`, 'Default container limits', 'Network policy: deny ingress except same namespace', `Pod Security: ${e.protected ? 'restricted' : 'baseline'}`, 'Service account “deployer” + namespace-only Role'],
          })),
        }],
      },
      access: [
        { who: 'You', how: 'your kubeconfig identity', what: 'use kubectl --as=system:serviceaccount:<namespace>:deployer to deploy exactly as that environment’s deployer' },
        { who: 'deployer (per namespace)', how: 'create/update workloads, services, config and secrets in its own namespace', what: 'cannot read or change other namespaces or cluster-wide objects' },
      ],
      why: ['Namespace per environment: quota, network rules and access are scoped to it.', 'Default-deny networking: nothing talks to dev from prod by accident.', 'Strict Pod Security on production-like namespaces.'],
    };
    return { architecture, steps, targets, warnings: [], blockers, prerequisites: ['Cluster-admin (or rights to create namespaces, quotas, network policies and roles)'], summary: `${envs.length} namespace(s) on ${context}` };
  }

  return { discover, plan };
};
