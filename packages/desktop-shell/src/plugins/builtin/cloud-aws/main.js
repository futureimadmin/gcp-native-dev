/** AWS connector. Identity = an AWS CLI profile (IAM Identity Center / SSO or static keys configured by the user). */
const fs = require('fs');
const path = require('path');
const { spawn } = require('child_process');

exports.activate = (ctx) => {
  const { exec, commandLine, isMissing } = ctx;

  const PROFILE_RE = /^[A-Za-z0-9_.-]{1,64}$/;
  const REGION_RE = /^[a-z]{2}(-[a-z]+)+-\d$/;
  const NAME_RE = /^[a-z0-9][a-z0-9._-]{1,61}[a-z0-9]$/;

  const profile = () => ctx.settings.get('profile', '') || '';
  const pArg = (p) => (p ? [`--profile=${p}`] : []);
  const aws = (proj, args) => commandLine('aws', [...args, ...pArg(proj.scope), `--region=${proj.region}`]);

  async function regionOf(p) {
    const r = await exec('aws', ['configure', 'get', 'region', ...pArg(p)], { timeout: 15000 });
    return r.ok && REGION_RE.test(r.out) ? r.out : '';
  }

  async function isSso(p) {
    for (const k of ['sso_session', 'sso_start_url']) {
      const r = await exec('aws', ['configure', 'get', k, ...pArg(p)], { timeout: 15000 });
      if (r.ok && r.out) return true;
    }
    return false;
  }

  /** One inventory probe. AccessDenied => hidden (least privilege); other failures are reported. */
  const PROBES = [
    { c: 'Compute', t: 'EC2 instances', cmd: ['ec2', 'describe-instances', '--query', 'Reservations[].Instances[].InstanceId'], url: (r) => `https://${r}.console.aws.amazon.com/ec2/home?region=${r}#Instances` },
    { c: 'Compute', t: 'Lambda functions', cmd: ['lambda', 'list-functions', '--query', 'Functions[].FunctionName'], url: (r) => `https://${r}.console.aws.amazon.com/lambda/home?region=${r}#/functions` },
    { c: 'Containers', t: 'ECS clusters', cmd: ['ecs', 'list-clusters', '--query', 'clusterArns'], url: (r) => `https://${r}.console.aws.amazon.com/ecs/v2/clusters?region=${r}` },
    { c: 'Containers', t: 'EKS clusters', cmd: ['eks', 'list-clusters', '--query', 'clusters'], url: (r) => `https://${r}.console.aws.amazon.com/eks/home?region=${r}#/clusters` },
    { c: 'Containers', t: 'ECR repositories', cmd: ['ecr', 'describe-repositories', '--query', 'repositories[].repositoryName'], url: (r) => `https://${r}.console.aws.amazon.com/ecr/repositories?region=${r}` },
    { c: 'Storage & Databases', t: 'S3 buckets', cmd: ['s3api', 'list-buckets', '--query', 'Buckets[].Name'], url: () => 'https://s3.console.aws.amazon.com/s3/home' },
    { c: 'Storage & Databases', t: 'RDS instances', cmd: ['rds', 'describe-db-instances', '--query', 'DBInstances[].DBInstanceIdentifier'], url: (r) => `https://${r}.console.aws.amazon.com/rds/home?region=${r}#databases:` },
    { c: 'Storage & Databases', t: 'DynamoDB tables', cmd: ['dynamodb', 'list-tables', '--query', 'TableNames'], url: (r) => `https://${r}.console.aws.amazon.com/dynamodbv2/home?region=${r}#tables` },
    { c: 'Messaging', t: 'SQS queues', cmd: ['sqs', 'list-queues', '--query', 'QueueUrls'], url: (r) => `https://${r}.console.aws.amazon.com/sqs/v3/home?region=${r}` },
    { c: 'Messaging', t: 'SNS topics', cmd: ['sns', 'list-topics', '--query', 'Topics[].TopicArn'], url: (r) => `https://${r}.console.aws.amazon.com/sns/v3/home?region=${r}#/topics` },
    { c: 'Security', t: 'Secrets Manager secrets', cmd: ['secretsmanager', 'list-secrets', '--query', 'SecretList[].Name'], url: (r) => `https://${r}.console.aws.amazon.com/secretsmanager/listsecrets?region=${r}` },
  ];

  const RESOURCES = {
    bucket: { label: 'S3 bucket', name: (p) => `${p.service}-${p.env}-data`, args: (p, n) => ['s3', 'mb', `s3://${n}`] },
    registry: { label: 'ECR repository', name: (p) => p.repo, args: (p, n) => ['ecr', 'create-repository', `--repository-name=${n}`, `--tags=Key=environment,Value=${p.env}`] },
    topic: { label: 'SNS topic', name: (p) => `${p.service}-${p.env}-events`, args: (p, n) => ['sns', 'create-topic', `--name=${n}`, `--tags=Key=environment,Value=${p.env}`] },
    queue: { label: 'SQS queue', name: (p) => `${p.service}-${p.env}-queue`, args: (p, n) => ['sqs', 'create-queue', `--queue-name=${n}`] },
    secret: { label: 'Secrets Manager secret', name: (p) => `${p.service}-${p.env}-secret`, args: (p, n) => ['secretsmanager', 'create-secret', `--name=${n}`] },
  };

  const buildspec = () => [
    '# Generated by Cloud Native Studio (AWS CodeBuild)',
    'version: 0.2',
    'env:',
    '  variables:',
    '    SERVICE: app',
    '    ENVIRONMENT: dev',
    'phases:',
    '  pre_build:',
    '    commands:',
    '      - ACCOUNT=$(aws sts get-caller-identity --query Account --output text)',
    '      - REGISTRY=$ACCOUNT.dkr.ecr.$AWS_DEFAULT_REGION.amazonaws.com',
    '      - aws ecr get-login-password | docker login --username AWS --password-stdin $REGISTRY',
    '  build:',
    '    commands:',
    '      - docker build -t $REGISTRY/$SERVICE-$ENVIRONMENT:$CODEBUILD_RESOLVED_SOURCE_VERSION .',
    '  post_build:',
    '    commands:',
    '      - docker push $REGISTRY/$SERVICE-$ENVIRONMENT:$CODEBUILD_RESOLVED_SOURCE_VERSION',
    '',
  ].join('\n');

  ctx.cloud.register({
    id: 'aws', name: 'Amazon Web Services', short: 'AWS', kind: 'public', color: '#ff9900',
    cli: { cmd: 'aws', install: 'https://aws.amazon.com/cli/' },
    scopeLabel: 'Profile',
    defaultRegion: 'us-east-1',
    regions: ['us-east-1', 'us-east-2', 'us-west-2', 'eu-west-1', 'eu-central-1', 'ap-south-1', 'ap-southeast-1', 'ap-southeast-2'],
    validateScope: (s) => PROFILE_RE.test(s),
    validateRegion: (r) => REGION_RE.test(r),
    consoleUrl: (scope, region) => `https://${region || 'us-east-1'}.console.aws.amazon.com/console/home?region=${region || 'us-east-1'}`,

    async status() {
      const p = profile();
      const r = await exec('aws', ['sts', 'get-caller-identity', '--output', 'json', ...pArg(p)], { timeout: 30000 });
      if (isMissing(r)) return { installed: false, signedIn: false, identity: '', scope: '', detail: 'AWS CLI not found' };
      if (!r.ok) return { installed: true, signedIn: false, identity: '', scope: p, detail: /expired|token|SSO|login/i.test(r.err) ? 'Session expired. Sign in again.' : 'Not signed in' };
      let id = {};
      try { id = JSON.parse(r.out); } catch { /* ignore */ }
      const region = await regionOf(p);
      return { installed: true, signedIn: true, identity: id.Arn || id.UserId || 'AWS identity', scope: p || 'default', detail: `Account ${id.Account || '?'}${region ? ` · ${region}` : ''}`, account: id.Account || '', region };
    },

    login(emit) {
      const p = profile() || 'default';
      isSso(p).then((sso) => {
        if (sso) {
          const child = spawn(commandLine('aws', ['sso', 'login', ...pArg(p)]), { shell: true, windowsHide: false });
          child.stdout.on('data', (d) => emit('log', d.toString()));
          child.stderr.on('data', (d) => emit('log', d.toString()));
          child.on('error', (e) => emit('log', `aws error: ${e.message}`));
          child.on('close', (code) => emit('done', code));
        } else {
          // No SSO configured for this profile: guide the user through the AWS CLI's own interactive setup.
          ctx.openTerminal('AWS sign-in', 'aws configure sso', ctx.workspace() || undefined);
          emit('log', 'A terminal window opened running "aws configure sso". Complete the prompts there, then click Refresh.');
          emit('done', 0);
        }
      });
    },

    async logout() {
      const p = profile();
      if (await isSso(p)) await exec('aws', ['sso', 'logout'], { timeout: 20000 });
    },

    async scopes() {
      const r = await exec('aws', ['configure', 'list-profiles'], { timeout: 20000 });
      if (!r.ok) throw new Error(isMissing(r) ? 'AWS CLI not found.' : r.err);
      const names = r.out.split(/\r?\n/).map((s) => s.trim()).filter((s) => PROFILE_RE.test(s));
      return (names.length ? names : ['default']).map((n) => ({ id: n, name: n, detail: 'AWS CLI profile' }));
    },

    async setScope(id) {
      if (!PROFILE_RE.test(id)) throw new Error('Invalid profile name.');
      ctx.settings.set('profile', id);
      return { region: await regionOf(id) };
    },

    async inventory(scope, opts) {
      const region = (opts && opts.region) || (await regionOf(scope)) || 'us-east-1';
      const out = await Promise.all(PROBES.map(async (pr) => {
        const r = await exec('aws', [...pr.cmd, '--output', 'json', ...pArg(scope), `--region=${region}`], { timeout: 30000 });
        if (!r.ok) return /AccessDenied|UnauthorizedOperation|not authorized/i.test(r.err) ? null : { category: pr.c, title: pr.t, detail: 'unavailable', error: r.err.split(/\r?\n/)[0].slice(0, 120), url: pr.url(region) };
        let n = 0;
        try { const j = JSON.parse(r.out); n = Array.isArray(j) ? j.length : 0; } catch { /* ignore */ }
        return { category: pr.c, title: pr.t, detail: `${n} found`, count: n, url: pr.url(region) };
      }));
      return out.filter(Boolean);
    },

    actions: {
      generatePipeline: () => ({ path: 'buildspec.yml', content: buildspec() }),

      // Starts an existing CodeBuild project named <service>-<env>.
      pipeline: (proj) => ({
        title: `CodeBuild ${proj.service}-${proj.env}`,
        command: aws(proj, ['codebuild', 'start-build', `--project-name=${proj.service}-${proj.env}`, '--environment-variables-override', `name=SERVICE,value=${proj.service},type=PLAINTEXT`, `name=ENVIRONMENT,value=${proj.env},type=PLAINTEXT`]),
      }),

      // SAM-based deploy; requires template.yaml (New Project > AWS Lambda (SAM) creates one).
      deploy: (proj, ws) => {
        if (!fs.existsSync(path.join(ws, 'template.yaml'))) throw new Error('No SAM template.yaml in this project. Use File > New Project > "AWS Lambda (SAM)" or add a template.yaml.');
        const stack = `${proj.service}-${proj.env}`;
        const p = proj.scope ? ` --profile ${proj.scope}` : '';
        return {
          title: `SAM deploy ${stack}`,
          command: `sam build && sam deploy --stack-name ${stack} --region ${proj.region}${p} --resolve-s3 --capabilities CAPABILITY_IAM --no-confirm-changeset --no-fail-on-empty-changeset --tags environment=${proj.env}`,
        };
      },

      resourceKinds: (proj) => Object.entries(RESOURCES).map(([id, r]) => ({ id, label: r.label, defaultName: r.name(proj) })),

      resource: (proj, params) => {
        const r = RESOURCES[params.type];
        if (!r) throw new Error('Unknown resource type.');
        const name = String(params.name || '').trim();
        if (!NAME_RE.test(name)) throw new Error('Name must be 3-63 characters: lowercase letters, digits, ".", "_" or "-".');
        return { title: `Create ${name}`, command: aws(proj, r.args(proj, name)) };
      },

      bootstrap: (proj, envs) => ({
        path: 'infra/cnd-bootstrap/aws/main.tf',
        content: [
          '# Generated by Cloud Native Studio (AWS)',
          'terraform {', '  required_providers { aws = { source = "hashicorp/aws", version = "~> 5.0" } }', '}',
          `provider "aws" {`, `  region  = "${proj.region}"`, proj.scope ? `  profile = "${proj.scope}"` : '', '}', '',
          ...envs.map((e) => `resource "aws_ecr_repository" "${e}" {\n  name = "${proj.service}-${e}"\n  tags = { environment = "${e}", managed-by = "cloud-native-studio" }\n}\n`),
        ].join('\n'),
      }),
    },
  });
};
