/**
 * Project & Environment Bootstrap
 * Creates GCP-native structure with environments: dev → sit → uat → prod
 */

import type { EnvironmentName } from '../cloud/types';

import { DEFAULT_ENVIRONMENTS } from '../cloud/types';

export const DEFAULT_SERVICES = [
  'cloudbuild.googleapis.com',
  'cloudfunctions.googleapis.com',
  'storage.googleapis.com',
  'firestore.googleapis.com',
  'sqladmin.googleapis.com',
  'aiplatform.googleapis.com',
  'bigquery.googleapis.com',
  'artifactregistry.googleapis.com',
  'secretmanager.googleapis.com',
  'iam.googleapis.com',
  'iamcredentials.googleapis.com',
  'logging.googleapis.com',
  'cloudtrace.googleapis.com',
  'run.googleapis.com',
  'container.googleapis.com',
] as const;

export interface BootstrapOptions {
  projectId: string;
  projectDisplayName?: string;
  createDefaultEnvironments?: boolean;
  environments?: EnvironmentName[];
  enableDefaultServices?: boolean;
  region?: string;
  githubRepo?: string;
}

export interface EnvironmentConfig {
  name: EnvironmentName;
  resourcePrefix: string;
  serviceAccountId: string;
  labels: Record<string, string>;
}

export interface BootstrapPlan {
  projectId: string;
  environments: EnvironmentConfig[];
  servicesToEnable: string[];
  terraformSnippet: string;
  summary: string[];
}

export function createBootstrapPlan(options: BootstrapOptions): BootstrapPlan {
  const envs =
    options.createDefaultEnvironments !== false
      ? options.environments || DEFAULT_ENVIRONMENTS
      : options.environments || ['dev'];
  const region = options.region || 'us-central1';
  const prefix = options.projectId.replace(/[^a-z0-9-]/gi, '-').toLowerCase().slice(0, 20);

  const environments: EnvironmentConfig[] = envs.map((name) => ({
    name,
    resourcePrefix: `${prefix}-${name}`,
    serviceAccountId: `cnd-${name}-sa`,
    labels: { environment: name, 'managed-by': 'gcp-native-dev', project: options.projectId },
  }));

  const servicesToEnable =
    options.enableDefaultServices !== false ? [...DEFAULT_SERVICES] : [];

  const summary = [
    `Project: ${options.projectId}`,
    `Environments: ${environments.map((e) => e.name).join(', ')}`,
    `Default services: ${servicesToEnable.length} APIs`,
    `Region: ${region}`,
  ];

  const terraformSnippet = generateTerraform(options, environments, servicesToEnable, region);
  return { projectId: options.projectId, environments, servicesToEnable, terraformSnippet, summary };
}

function generateTerraform(
  options: BootstrapOptions,
  environments: EnvironmentConfig[],
  services: string[],
  region: string
): string {
  const saBlocks = environments
    .map(
      (env) => `
resource "google_service_account" "${env.name}" {
  account_id   = "${env.serviceAccountId}"
  display_name = "CND ${env.name.toUpperCase()} environment"
  project      = var.project_id
}
`
    )
    .join('\n');

  const apiBlocks = services
    .map(
      (svc, i) => `
resource "google_project_service" "api_${i}" {
  project = var.project_id
  service = "${svc}"
  disable_on_destroy = false
}`
    )
    .join('\n');

  return `# Generated by GCP Native Dev IDE
variable "project_id" { type = string
  default = "${options.projectId}" }
variable "region" { type = string
  default = "${region}" }
${apiBlocks}
${saBlocks}
`;
}

export function describeDefaultSetup(): string {
  return [
    'Default setup creates environments: dev → sit → uat → prod',
    'Per environment: least-privilege SA for Run, Functions, Storage, Firestore, Gemini, BigQuery, Artifact Registry, Secret Manager, Logging, Trace',
    'Shared: Cloud Build, Artifact Registry, required APIs',
  ].join('\n');
}
